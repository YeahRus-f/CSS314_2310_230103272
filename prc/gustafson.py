# 6. Tasks 22–23 — Multiprocessing benchmark

def workload(k):
    total = 0.0
    for i in range(1, k + 1):
        total += math.sqrt(i) * math.sin(i)
    return total

def benchmark(processes, k=300000, repeats=5):
    times = []
    for _ in range(repeats):
        start = time.perf_counter()
        with mp.Pool(processes=processes) as pool:
            pool.map(workload, [k] * processes)
        times.append(time.perf_counter() - start)
    return times

hardware = os.cpu_count() or 2
counts = list(range(1, min(hardware, 8) + 1))

benchmark_rows = []
for count in counts:
    measurements = benchmark(count)
    benchmark_rows.append({
        "Processes": count,
        "Mean time": np.mean(measurements),
        "Std time": np.std(measurements, ddof=1) if len(measurements) > 1 else 0
    })

bench_df = pd.DataFrame(benchmark_rows)
bench_df["Speedup"] = bench_df["Mean time"].iloc[0] / bench_df["Mean time"]
bench_df["Efficiency"] = bench_df["Speedup"] / bench_df["Processes"]
bench_df.to_csv(ROOT / "benchmarks" / "results.csv", index=False)

# Estimate observed alpha by least-squares fitting:
# S(P) = P - alpha(P - 1)
x = bench_df["Processes"].to_numpy() - 1
y = bench_df["Processes"].to_numpy() - bench_df["Speedup"].to_numpy()
alpha_observed = np.sum(x*y) / np.sum(x*x) if np.sum(x*x) else 0

