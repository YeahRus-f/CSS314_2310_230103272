"""TASK 3 — Cache Line Contention (False Sharing).

CPython threads are serialized by the GIL, so true simultaneous writes to one
cache line are impossible with threading. We therefore use PROCESSES that share
one block of memory (multiprocessing.RawArray of int64):

  1) Unpadded shared : counter i at offset i*8 bytes  -> all counters in ONE 64-byte line
  2) Padded shared   : counter i at offset i*64 bytes -> each counter in its OWN line
  3) Local variable  : increment a local, write shared_counts[i] once at the end
"""
import time
import multiprocessing as mp
# ---------------- helpers (student ID, hardware info, output log) ----------------
import os
