ITERS = 50_000_000      # increments per worker (lower it if your PC is slow)
PAD = 8                 # 8 x int64 = 64 bytes = one cache line


def worker_shared(buf, idx, stride, iters, barrier, times):
    arr = memoryview(buf).cast("B").cast("q")
    pos = idx * stride
    barrier.wait()
    t0 = time.perf_counter()
    for _ in range(iters):
        arr[pos] += 1                   # every increment writes to shared memory
    t1 = time.perf_counter()
    times[2 * idx] = t0
    times[2 * idx + 1] = t1


def worker_local(buf, idx, stride, iters, barrier, times):
    arr = memoryview(buf).cast("B").cast("q")
    pos = idx * stride
    barrier.wait()
    t0 = time.perf_counter()
    local = 0
    for _ in range(iters):
        local += 1                      # private variable, no cache traffic
    arr[pos] = local                    # single write at the very end
    t1 = time.perf_counter()
    times[2 * idx] = t0
    times[2 * idx + 1] = t1


def run(target, n, stride, iters):
    buf = mp.RawArray("q", n * stride)          # shared_counts
    times = mp.RawArray("d", 2 * n)
    barrier = mp.Barrier(n)
    procs = [mp.Process(target=target, args=(buf, i, stride, iters, barrier, times))
             for i in range(n)]
    for p in procs:
        p.start()
    for p in procs:
        p.join()
    starts, ends = times[0::2], times[1::2]
    counts = [buf[i * stride] for i in range(n)]
    assert all(c == iters for c in counts), f"bad counts {counts}"
    return max(ends) - min(starts)


def main():
    start_log("task3_output.txt")
    header("TASK 3 — Cache Line Contention (False Sharing)")

    n = physical_cores()
    print(f"Workers N = {n} (physical cores) | {ITERS:,} increments per worker")
    print("Workers are processes sharing one memory block (GIL-free true parallelism)\n")

    t_unpadded = run(worker_shared, n, 1, ITERS)
    print(f"[1] Unpadded shared array (8 B apart, same cache line): {t_unpadded * 1000:>10.1f} ms")
    t_padded = run(worker_shared, n, PAD, ITERS)
    print(f"[2] Padded shared array   (64 B apart, own cache line): {t_padded * 1000:>10.1f} ms")
    t_local = run(worker_local, n, PAD, ITERS)
    print(f"[3] Local variable, single write at the end           : {t_local * 1000:>10.1f} ms")

    print("\nExecution ratio:")
    print(f"  Unpadded / Padded = {t_unpadded / t_padded:.2f}x")
    print(f"  Unpadded / Local  = {t_unpadded / t_local:.2f}x")
    print("\nConclusion: when counters share a 64-byte cache line, every write by one core "
          "invalidates that line in the other cores' L1/L2 (MESI ping-pong). Padding or "
          "local accumulation removes the contention. Python interpreter overhead per "
          "iteration hides part of the effect; in C/Numba the ratio is much larger.")


if __name__ == "__main__":
    main()

