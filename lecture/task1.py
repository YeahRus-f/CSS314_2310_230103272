"""TASK 1 — Hardware Probe & Serial Baseline."""
import time
import numpy as np
# ---------------- helpers (student ID, hardware info, output log) ----------------
import os
import sys
import platform
import subprocess

STUDENT_ID = 230103272


class Tee:
    """Duplicates everything printed to the console into taskN_output.txt (UTF-8)."""

    def __init__(self, path):
        self.file = open(path, "w", encoding="utf-8")
        self.console = sys.stdout

    def write(self, s):
        self.console.write(s)
        self.file.write(s)

    def flush(self):
        self.console.flush()
        self.file.flush()



def start_log(filename):
    """Save output in the current Google Colab working directory."""
    path = os.path.abspath(filename)
    sys.stdout = Tee(path)



def cpu_model():
    system = platform.system()
    try:
        if system == "Windows":
            import winreg
            key = winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,
                                 r"HARDWARE\DESCRIPTION\System\CentralProcessor\0")
            return winreg.QueryValueEx(key, "ProcessorNameString")[0].strip()
        if system == "Linux":
            with open("/proc/cpuinfo") as f:
                for line in f:
                    if line.lower().startswith("model name"):
                        return line.split(":", 1)[1].strip()
        if system == "Darwin":
            return subprocess.check_output(
                ["sysctl", "-n", "machdep.cpu.brand_string"], text=True).strip()
    except Exception:
        pass
    return platform.processor() or platform.machine() or "unknown"


def logical_cores():
    return os.cpu_count() or 1


def physical_cores():
    try:
        import psutil
        n = psutil.cpu_count(logical=False)
        if n:
            return n
    except Exception:
        pass
    return logical_cores()  # fallback if psutil is not installed


def header(task_title):
    print("=" * 64)
    print(task_title)
    print("=" * 64)
    print(f"Student ID     : {STUDENT_ID}")
    print(f"OS             : {platform.system()} {platform.release()} ({platform.version()})")
    print(f"Platform       : {platform.platform()}")
    print(f"CPU model      : {cpu_model()}")
    print(f"Logical cores  : {logical_cores()}  (os.cpu_count())")
    print(f"Physical cores : {physical_cores()}")
    print(f"Python         : {platform.python_version()}")
    print("-" * 64)
# ---------------------------------------------------------------------------------


N = 20_000_000


def main():
    start_log("task1_output.txt")
    header("TASK 1 — Hardware Probe & Serial Baseline")

    rng = np.random.default_rng(STUDENT_ID)        # seed = Student ID
    data = rng.random(N, dtype=np.float64)          # 20,000,000 float64
    print(f"Array: {N:,} elements, dtype={data.dtype}, seed={STUDENT_ID}, "
          f"size={data.nbytes / 1e6:.1f} MB")

    # numpy reductions (sum / std) run in ONE thread -> strictly serial
    t0 = time.perf_counter()
    total = float(np.sum(data))
    std = float(np.std(data))
    t1 = time.perf_counter()

    print(f"Sum            : {total:.6f}")
    print(f"Std deviation  : {std:.10f}")
    print(f"Wall-clock time: {(t1 - t0) * 1000:.3f} ms (serial, 1 thread)")


if __name__ == "__main__":
    main()

